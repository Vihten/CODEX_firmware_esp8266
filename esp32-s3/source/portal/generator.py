"""Assemble the portal's shared lexical fragments into one shipped script.

Build integration: ``from portal.generator import sync; sync(web_root)``.
No JavaScript imports, runtime loader, minifier, or third-party packages.
"""

import argparse
import json
from pathlib import Path
import sys


SOURCE_ROOT = Path(__file__).resolve().parent
WEB_ROOT = SOURCE_ROOT.parent / "web"
MESSAGE_KEYS = (
    "missing", "on", "off", "online", "offline", "remainingLastData",
    "resetUnknown", "ageUnknown", "stale", "resetPrefix", "agePrefix",
    "ageSuffix", "seconds", "minutes", "hours",
)
STRINGS_MARKER = "    // @portal-strings\n"
FRAGMENTS = (
    "context.js",
    "commands.js",
    "settings.js",
    "stats.js",
    "agents.js",
    "controls.js",
    "lifecycle.js",
)
HEADER = (
    "// Generated by portal/generator.py. Edit portal/*.js, then regenerate.\n"
    "(() => {\n"
    "  'use strict';\n"
    "  const start = () => {\n"
)
FOOTER = (
    "  };\n"
    "  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start, {once: true});\n"
    "  else start();\n"
    "})();\n"
)


def load_messages(source_root: Path = SOURCE_ROOT) -> dict:
    """Read the sole shared-string authority, rejecting ambiguous input."""
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"Duplicate portal message key: {key}")
            result[key] = value
        return result

    messages = json.loads((Path(source_root) / "messages.uk.json").read_text(encoding="utf-8"),
                          object_pairs_hook=unique)
    if not isinstance(messages, dict) or set(messages) != set(MESSAGE_KEYS):
        raise ValueError("Portal messages must contain exactly the documented shared keys")
    for key, value in messages.items():
        if not isinstance(value, str) or not value or any(ord(char) < 32 for char in value):
            raise ValueError(f"Portal message {key} must be nonempty single-line text")
        value.encode("utf-8")
    return {key: messages[key] for key in MESSAGE_KEYS}


def render_header(source_root: Path = SOURCE_ROOT) -> bytes:
    """Return a heap-free C++ header; keys and UTF-8 values match JavaScript."""
    lines = ["// Generated by portal/generator.py from portal/messages.uk.json.\n",
             "#pragma once\n\n", "namespace portal_strings {\n"]
    for key, value in load_messages(source_root).items():
        lines.append(f"static constexpr char {key}[] = {json.dumps(value, ensure_ascii=False)};\n")
    lines.append("}  // namespace portal_strings\n")
    return "".join(lines).encode("utf-8")


def render(source_root: Path = SOURCE_ROOT) -> bytes:
    """Return deterministic UTF-8/LF JavaScript without touching the output.

    All fragments live inside the same start() closure. Their order is explicit:
    context initializes shared state; commands, settings, stats, agents and
    controls declare behavior; lifecycle initializes polling and starts last.
    Cross-fragment references must only execute after their bindings initialize.
    """
    source_root = Path(source_root)
    actual = {path.name for path in source_root.glob("*.js")}
    expected = set(FRAGMENTS)
    if actual != expected:
        raise ValueError(
            f"Portal fragment manifest mismatch: missing={sorted(expected - actual)}, "
            f"unlisted={sorted(actual - expected)}"
        )
    chunks = [HEADER]
    messages = json.dumps(load_messages(source_root), ensure_ascii=False, separators=(",", ":"))
    # Keep this valid in browsers that treat literal Unicode line separators as
    # source newlines. The JSON authority remains readable UTF-8.
    messages = messages.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    for name in FRAGMENTS:
        text = (source_root / name).read_text(encoding="utf-8")
        if not text.strip():
            raise ValueError(f"Empty portal fragment: {name}")
        if name == "context.js":
            if text.count(STRINGS_MARKER) != 1:
                raise ValueError("context.js must contain exactly one portal strings marker")
            text = text.replace(STRINGS_MARKER, f"    const portalStrings = Object.freeze({messages});\n")
        chunks.append(f"    // Source: portal/{name}\n")
        chunks.append(text.rstrip("\n") + "\n")
    chunks.append(FOOTER)
    return "".join(chunks).encode("utf-8")


def sync(web_root: Path = WEB_ROOT, *, check: bool = False) -> bool:
    """Sync portal.js and sibling main/portal_strings.hpp; return any change.

    The canonical source is always beside this generator, independent of cwd.
    An explicit web_root also permits bundle staging trees. Identical output is
    left untouched so incremental builds retain its mtime. In check mode, stale
    or missing output raises ValueError and no directories/files are modified.
    """
    web_root = Path(web_root)
    outputs = (
        (web_root / "assets/js/portal.js", render(), "portal script"),
        (web_root.parent / "main/portal_strings.hpp", render_header(), "portal strings header"),
    )
    stale = [(target, data, label) for target, data, label in outputs
             if not target.is_file() or target.read_bytes() != data]
    if check and stale:
        raise ValueError("\n".join(f"Stale generated {label}: {target}; run portal/generator.py"
                                   for target, _, label in stale))
    for target, data, _ in stale:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    return bool(stale)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on stale output without writing")
    parser.add_argument("--web-root", type=Path, default=WEB_ROOT, help="destination web tree")
    args = parser.parse_args(argv)
    try:
        changed = sync(args.web_root, check=args.check)
    except (OSError, UnicodeError, ValueError) as error:
        print(str(error), file=sys.stderr)
        return 1
    print("Portal script and strings header: " + ("generated" if changed else "current"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
